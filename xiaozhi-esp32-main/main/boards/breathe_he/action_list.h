#include <cstdint>

// Panda action system — 3x 270° servos (breathe_he board)
// Servo order: Head(IO15), LeftHand(IO16), RightHand(IO17)
// Head(IO15): -135=left, 0=center, +135=right
// LeftHand(IO16): -95=crawl down, 0=neutral, +90=compress(breathe)
// RightHand(IO17): +95=crawl down, 0=neutral, -90=compress(breathe)
// Breathing: both hands compress together (LH=+90, RH=-90)
// Crawling: hands push down (LH=-95, RH=+95)

#define STEP_MS 100
#define GROUP_HEAD        0x01  // bit 0: Head servo
#define GROUP_LEFT_HAND   0x02  // bit 1: Left hand servo
#define GROUP_RIGHT_HAND  0x04  // bit 2: Right hand servo
#define GROUP_HANDS       0x06  // bits 1+2: Both hands
#define GROUP_ALL         0x07  // bits 0+1+2: All 3 servos

template<int N> struct ServoActionStep { int16_t angles[N]; };
struct ServoActionSeries { const int16_t* data; uint8_t total_steps; };
struct ServoAction { const char* name; uint16_t id; const ServoActionSeries* series; uint8_t series_count; uint8_t group_mask; };

